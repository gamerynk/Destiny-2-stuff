import argparse
import json
from pathlib import Path

from audit_controller import controller_rows
from inspect_modes import fnv1
from package_reader import Packages


ROLE_NAMES = (
    *(f'pvp_controller.placements_capture_zones.zones[{i}]' for i in range(3)),
    *(f'pvp_controller.mode_demolition.bomb_plant_zones[{i}]' for i in range(2)),
    *(f'pvp_controller.mode_demolition.bomb_objects[{i}]' for i in range(2)),
    *(f'pvp_controller.mode_breakthrough.home_bases[{i}]' for i in range(2)),
    'pvp_controller.mode_breakthrough.neutral_base',
    *(f'pvp_controller.mode_breakthrough.ho_team_allegiance[{i}]' for i in range(2)),
    *(f'pvp_controller.mode_breakthrough.of_team_allegiance[{i}]' for i in range(2)),
    *(f'pvp_controller.mode_breakthrough.toggle_side_influence[{i}]' for i in range(2)),
    *(f'pvp_controller.m_directive_sensor_team_{i:02}' for i in range(12)),
    *(f'pvp_controller.team_filters[{i}]' for i in range(2)),
    'pvp_controller.modes.mode_supremacy.ho_spawn',
    'pvp_controller.modes.mode_supremacy.of_spawn',
)

SCHEMAS = {
    4: (0x80809927, 0x8080992F),
    26: (0x8080953F, 0x8080954B),
    32: (0x80809556, 0x8080955A),
    34: (0x80809568, 0x8080956A),
    68: (0x80804F53, 0x80804F67),
}


def extract(packages, catalog):
    result = []
    schemas = {}
    for item in catalog['maps']:
        rows = controller_rows(packages, item['scenario_tag'])
        key = next(row['key'] for row in rows
                   if row.get('name') == 'pvp_controller.pvp_music')
        by_name = {row.get('name'): row for row in rows if row.get('name')}
        bindings = []
        for name in ROLE_NAMES:
            row = by_name.get(name)
            if row is None or row['key'] != key or row['index'] > 0x7FFF:
                raise ValueError(f"{item['name']}: missing {name}")
            expected = SCHEMAS.get(row['type'])
            if expected != (row.get('component'), row.get('auth')):
                raise ValueError(f"{item['name']}: schema mismatch for {name}")
            if fnv1(name.encode('ascii')) != row['name_hash']:
                raise ValueError(f"{item['name']}: hash mismatch for {name}")
            signature = (row['type'], row['component'], row['auth'])
            if name in schemas and schemas[name] != signature:
                raise ValueError(f'Variable schema for {name}')
            schemas[name] = signature
            bindings.append(row['index'])
        result.append({'scenario_name': item['name'],
                       'scenario_tag': item['scenario_tag'],
                       'registry_key': key,
                       'slot_indices': bindings})
    if len(result) != 31 or len(ROLE_NAMES) != 32:
        raise ValueError('Objective binding count changed')
    return {'format': 1, 'source_executable_sha256': catalog['executable_sha256'],
            'role_names': list(ROLE_NAMES),
            'role_schema': [{'slot_type': schemas[name][0],
                             'component_class': schemas[name][1],
                             'auth_class': schemas[name][2],
                             'name_hash': fnv1(name.encode('ascii'))}
                            for name in ROLE_NAMES],
            'maps': result}


def render_inc(report):
    lines = ['// Generated by tools/crucible/extract_objective_bindings.py.',
             '// Installed v38 metadata only; no auth body or game rule is enabled here.',
             'constexpr std::array<ObjectiveLayout, 31> kObjectiveLayouts{{']
    for item in report['maps']:
        indices = ', '.join(f'{index}U' for index in item['slot_indices'])
        lines.append(f'    {{0x{item["scenario_tag"]:08X}U, '
                     f'0x{item["registry_key"]:08X}U, {{{indices}}}}},')
    lines.append('}};')
    lines.append('constexpr std::array<RoleSchema, 32> kObjectiveRoleSchemas{{')
    for item in report['role_schema']:
        lines.append(f'    {{{item["slot_type"]}U, '
                     f'0x{item["component_class"]:08X}U, '
                     f'0x{item["auth_class"]:08X}U, '
                     f'0x{item["name_hash"]:08X}U}},')
    lines.extend(['}};', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--game-root', type=Path, required=True)
    parser.add_argument('--pid', type=int, required=True)
    parser.add_argument('--catalog', type=Path,
                        default=Path('docs/crucible/native-maps.json'))
    parser.add_argument('--output', type=Path,
                        default=Path('docs/crucible/native-objectives.json'))
    parser.add_argument('--include', type=Path,
                        default=Path('dawn/src/state/activity/crucible/objective_bindings.inc'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    catalog = json.loads(args.catalog.read_text())
    report = extract(Packages(args.game_root, args.pid), catalog)
    outputs = {args.output: json.dumps(report, indent=2) + '\n',
               args.include: render_inc(report)}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Generated file is stale: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f'{len(report["maps"])} maps, {len(ROLE_NAMES)} objective bindings per map')


if __name__ == '__main__':
    main()
