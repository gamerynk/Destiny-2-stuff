import argparse
import json
from pathlib import Path
import struct


HEADER = '''// Generated by tools/crucible/generate_native_maps.py from docs/crucible/native-maps.json.
// Package-derived metadata only. Native spawn choice remains with the client.
#pragma once

#include <array>
#include <cstddef>
#include <cstdint>
#include <span>
#include <string_view>

namespace dawn::state::activity::crucible {{

inline constexpr std::string_view kSourceExecutableSha256 = "{digest}";
inline constexpr std::size_t kNativeMapCount = {maps};
inline constexpr std::size_t kNativeCombatSpawnCount = {spawns};
inline constexpr std::size_t kNativeTeamSpawnCount = {teams};
inline constexpr std::size_t kNativeArrivalPointCount = {arrivals};

struct NativeMap final {{
    std::string_view scenarioName;
    std::string_view displayName;
    std::uint32_t scenarioTag;
    std::uint32_t nameHash;
    std::uint32_t stringBankTag;
    std::uint16_t scenarioPackageId;
    std::size_t firstCombatSpawn;
    std::size_t combatSpawnCount;
    std::size_t firstArrivalPoint;
    std::size_t arrivalPointCount;
    std::size_t firstTeamSpawn;
    std::size_t teamSpawnCount;
}};

struct CombatSpawn final {{
    std::array<float, 3> position;
    std::array<float, 4> rotation;
    std::string_view authoredName;
    std::uint32_t nameHash;
    std::uint32_t placedTag;
    std::uint32_t objectTag;
    std::uint32_t registryTag;
    std::uint32_t registryKey;
    std::uint16_t slotIndex;
    std::int16_t bubbleIndex;
    std::int8_t team;
}};

using TeamSpawn = CombatSpawn;

struct ArrivalPoint final {{
    std::array<float, 3> position;
    std::array<float, 4> rotation;
    std::uint32_t nameHash;
    std::uint32_t setTag;
    std::uint16_t packageId;
}};

[[nodiscard]] std::span<const NativeMap> native_maps() noexcept;
[[nodiscard]] const NativeMap* find_native_map(std::string_view scenarioName) noexcept;
[[nodiscard]] const NativeMap* find_native_map(std::uint32_t scenarioTag) noexcept;
[[nodiscard]] std::span<const CombatSpawn> combat_spawns(const NativeMap& map) noexcept;
[[nodiscard]] std::span<const TeamSpawn> team_spawns(const NativeMap& map) noexcept;
[[nodiscard]] std::span<const ArrivalPoint> arrival_points(const NativeMap& map) noexcept;

}} // namespace dawn::state::activity::crucible
'''


def literal(value):
    return json.dumps(value, ensure_ascii=True)


def flt(value):
    if not isinstance(value, (int, float)):
        raise ValueError('Expected numeric coordinate')
    result = format(float(value), '.9g')
    if struct.pack('<f', float(result)) != struct.pack('<f', float(value)):
        raise ValueError('Rounded coordinate changed its authored float32 value')
    if '.' not in result and 'e' not in result:
        result += '.0'
    return result + 'f'


def vec(values):
    return '{{' + ', '.join(map(flt, values)) + '}}'


def generate(catalog):
    maps = catalog['maps']
    combat_count = sum(len(row['combat_spawns']) for row in maps)
    team_count = sum(len(row['team_spawns']) for row in maps)
    arrival_count = sum(len(s['points']) for row in maps for s in row['spawn_sets'])
    if (len(maps) != catalog['map_count'] or combat_count != catalog['combat_spawn_count']
            or team_count != catalog['team_spawn_count']
            or arrival_count != catalog['spawn_point_count']):
        raise ValueError('Catalog count mismatch')
    header = HEADER.format(digest=catalog['executable_sha256'], maps=len(maps),
                           spawns=combat_count, teams=team_count, arrivals=arrival_count)
    lines = [
        '// Generated by tools/crucible/generate_native_maps.py from docs/crucible/native-maps.json.',
        '#include "native_maps.h"',
        '',
        '#include <algorithm>',
        '#include <iterator>',
        '',
        'namespace dawn::state::activity::crucible {',
        'namespace {',
        'constexpr NativeMap kMaps[] = {',
    ]
    first_spawn = first_arrival = first_team = 0
    for row in maps:
        spawns = len(row['combat_spawns'])
        teams = len(row['team_spawns'])
        arrivals = sum(len(s['points']) for s in row['spawn_sets'])
        lines.append('    {' + ', '.join((literal(row['name']), literal(row['display_name']),
            str(row['scenario_tag']) + 'U', str(row['name_hash']) + 'U',
            str(row['string_bank']) + 'U', str((row['scenario_tag'] - 0x80800000) >> 13) + 'U',
            str(first_spawn) + 'U', str(spawns) + 'U',
            str(first_arrival) + 'U', str(arrivals) + 'U',
            str(first_team) + 'U', str(teams) + 'U')) + '},')
        first_spawn += spawns
        first_arrival += arrivals
        first_team += teams
    lines += ['};', 'constexpr CombatSpawn kCombatSpawns[] = {']
    for row in maps:
        for spawn in row['combat_spawns']:
            fields = (vec(spawn['position']), vec(spawn['rotation']), literal(spawn['name']),
                str(spawn['name_hash']) + 'U', str(spawn['placed_tag']) + 'U',
                str(spawn['object_tag']) + 'U', str(spawn['registry_tag']) + 'U',
                str(spawn['registry_key']) + 'U', str(spawn['slot_index']) + 'U',
                str(spawn['bubble_index']), str(spawn['team'] if spawn['team'] is not None else -1))
            lines.append('    {' + ', '.join(fields) + '},')
    lines += ['};', 'constexpr TeamSpawn kTeamSpawns[] = {']
    for row in maps:
        for spawn in row['team_spawns']:
            fields = (vec(spawn['position']), vec(spawn['rotation']), literal(spawn['name']),
                str(spawn['name_hash']) + 'U', str(spawn['placed_tag']) + 'U',
                str(spawn['object_tag']) + 'U', str(spawn['registry_tag']) + 'U',
                str(spawn['registry_key']) + 'U', str(spawn['slot_index']) + 'U',
                str(spawn['bubble_index']), str(spawn['team'] if spawn['team'] is not None else -1))
            lines.append('    {' + ', '.join(fields) + '},')
    lines += ['};', 'constexpr ArrivalPoint kArrivalPoints[] = {']
    for row in maps:
        for spawn_set in row['spawn_sets']:
            for point in spawn_set['points']:
                fields = (vec(point['position']), vec(point['rotation']),
                    str(point['name_hash']) + 'U', str(spawn_set['tag']) + 'U',
                    str(spawn_set['package_id']) + 'U')
                lines.append('    {' + ', '.join(fields) + '},')
    lines += [
        '};',
        'static_assert(std::size(kMaps) == kNativeMapCount);',
        'static_assert(std::size(kCombatSpawns) == kNativeCombatSpawnCount);',
        'static_assert(std::size(kTeamSpawns) == kNativeTeamSpawnCount);',
        'static_assert(std::size(kArrivalPoints) == kNativeArrivalPointCount);',
        'consteval bool valid_ranges() {',
        '    std::size_t combat = 0;',
        '    std::size_t arrivals = 0;',
        '    std::size_t teams = 0;',
        '    for (std::size_t i = 0; i < std::size(kMaps); ++i) {',
        '        const NativeMap& map = kMaps[i];',
        '        if (map.scenarioName.empty() || map.displayName.empty() || map.scenarioTag == 0',
        '            || map.combatSpawnCount == 0 || map.firstCombatSpawn != combat',
        '            || map.firstArrivalPoint != arrivals',
        '            || map.firstTeamSpawn != teams',
        '            || (i != 0 && kMaps[i - 1].scenarioName >= map.scenarioName)) {',
        '            return false;',
        '        }',
        '        combat += map.combatSpawnCount;',
        '        arrivals += map.arrivalPointCount;',
        '        teams += map.teamSpawnCount;',
        '    }',
        '    return combat == kNativeCombatSpawnCount && arrivals == kNativeArrivalPointCount',
        '        && teams == kNativeTeamSpawnCount;',
        '}',
        'static_assert(valid_ranges());',
        'static_assert(kMaps[20].scenarioName == "pvp_ness"',
        '    && kMaps[20].displayName == "Altar of Flame"',
        '    && kMaps[20].combatSpawnCount == 61);',
        'static_assert(kMaps[25].scenarioName == "pvp_shaft"',
        '    && kMaps[25].displayName == "Javelin-4"',
        '    && kMaps[25].combatSpawnCount == 35 && kMaps[25].teamSpawnCount == 50);',
        'static_assert(kMaps[30].scenarioName == "pvp_wilderness_town_2"',
        '    && kMaps[30].displayName == "Widow\'s Court"',
        '    && kMaps[30].combatSpawnCount == 38',
        '    && kMaps[30].arrivalPointCount == 0);',
        'static_assert(kCombatSpawns[1747].position[0] > 63.48f',
        '    && kCombatSpawns[1747].position[0] < 63.49f);',
        '} // namespace',
        '',
        'std::span<const NativeMap> native_maps() noexcept { return kMaps; }',
        '',
        'const NativeMap* find_native_map(std::string_view scenarioName) noexcept {',
        '    const auto rows = native_maps();',
        '    const auto found = std::lower_bound(rows.begin(), rows.end(), scenarioName,',
        '        [](const NativeMap& row, std::string_view key) { return row.scenarioName < key; });',
        '    return found != rows.end() && found->scenarioName == scenarioName ? &*found : nullptr;',
        '}',
        '',
        'const NativeMap* find_native_map(std::uint32_t scenarioTag) noexcept {',
        '    const auto rows = native_maps();',
        '    const auto found = std::find_if(rows.begin(), rows.end(),',
        '        [scenarioTag](const NativeMap& row) { return row.scenarioTag == scenarioTag; });',
        '    return found != rows.end() ? &*found : nullptr;',
        '}',
        '',
        'std::span<const CombatSpawn> combat_spawns(const NativeMap& map) noexcept {',
        '    if (map.firstCombatSpawn > kNativeCombatSpawnCount',
        '        || map.combatSpawnCount > kNativeCombatSpawnCount - map.firstCombatSpawn) {',
        '        return {};',
        '    }',
        '    return {kCombatSpawns + map.firstCombatSpawn, map.combatSpawnCount};',
        '}',
        '',
        'std::span<const TeamSpawn> team_spawns(const NativeMap& map) noexcept {',
        '    if (map.firstTeamSpawn > kNativeTeamSpawnCount',
        '        || map.teamSpawnCount > kNativeTeamSpawnCount - map.firstTeamSpawn) {',
        '        return {};',
        '    }',
        '    return {kTeamSpawns + map.firstTeamSpawn, map.teamSpawnCount};',
        '}',
        '',
        'std::span<const ArrivalPoint> arrival_points(const NativeMap& map) noexcept {',
        '    if (map.firstArrivalPoint > kNativeArrivalPointCount',
        '        || map.arrivalPointCount > kNativeArrivalPointCount - map.firstArrivalPoint) {',
        '        return {};',
        '    }',
        '    return {kArrivalPoints + map.firstArrivalPoint, map.arrivalPointCount};',
        '}',
        '',
        '} // namespace dawn::state::activity::crucible',
        '',
    ]
    return header, '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog', type=Path, default=Path('docs/crucible/native-maps.json'))
    parser.add_argument('--output-dir', type=Path,
        default=Path('dawn/src/state/activity/crucible'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    header, source = generate(json.loads(args.catalog.read_text()))
    for path, content in ((args.output_dir / 'native_maps.h', header),
                          (args.output_dir / 'native_maps.cpp', source)):
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f'Generated file differs: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('Generated map catalog matches' if args.check else 'Generated map catalog written')


if __name__ == '__main__':
    main()
