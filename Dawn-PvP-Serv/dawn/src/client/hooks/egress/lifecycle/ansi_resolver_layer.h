[[nodiscard]] inline bool verified_ansi_resolver_bytes(std::span<const unsigned char> code,
                                                       const void* wideTarget) noexcept {
    if (code.size() != kVerifiedAnsiResolverCode.size()
        || std::memcmp(code.data(), kVerifiedAnsiResolverCode.data(), code.size()) != 0) return false;
    constexpr std::size_t kWideCallOffset = 0xB8;
    std::int32_t displacement{};
    std::memcpy(&displacement, code.data() + kWideCallOffset + 1, sizeof(displacement));
    const auto callEnd = reinterpret_cast<std::uintptr_t>(code.data()) + kWideCallOffset + 5;
    return callEnd + static_cast<std::intptr_t>(displacement)
        == reinterpret_cast<std::uintptr_t>(wideTarget);
}

[[nodiscard]] inline bool native_ansi_uses_wide_guard(HMODULE module) noexcept {
    const auto* ansi = reinterpret_cast<const unsigned char*>(GetProcAddress(module, "getaddrinfo"));
    const auto* wide = reinterpret_cast<const void*>(GetProcAddress(module, "GetAddrInfoW"));
    if (ansi == nullptr || wide == nullptr) return false;
    MEMORY_BASIC_INFORMATION region{};
    if (VirtualQuery(ansi, &region, sizeof(region)) != sizeof(region)
        || region.AllocationBase != module || region.State != MEM_COMMIT
        || region.Type != MEM_IMAGE || (region.Protect & (PAGE_NOACCESS | PAGE_GUARD)) != 0
        || region.RegionSize < kVerifiedAnsiResolverCode.size()
        || reinterpret_cast<const unsigned char*>(region.BaseAddress) + region.RegionSize
           < ansi + kVerifiedAnsiResolverCode.size()) return false;
    return verified_ansi_resolver_bytes({ansi, kVerifiedAnsiResolverCode.size()}, wide);
}
